def tx(s):
    s = re.sub(r'\{([^}]*)\}', lambda m: re.sub(r'(?<=[A-Za-z)])(\d+)', r'<sub>\1</sub>', m.group(1)), s)
    return re.sub(r'\[(\d+),(\d+)\]', r'<sup>\1</sup><sub>\2</sub>', s)


